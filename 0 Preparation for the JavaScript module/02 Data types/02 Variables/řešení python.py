# Variable with number type
number = 10
print(number)
print(type(number))
# This variable's type is int, and it stores the value 10


# Variable with string type
string = "Hello"
print(string)
print(type(string))
# This variable's type is str, and it stores the value "Hello"


# Variable with number + string type
numberPlusString = str(2) + "two"
print(numberPlusString)
print(type(numberPlusString))
# This variable's type is str, and it stores the value "2two"


# Variable with boolean type
boolean = True
print(boolean)
print(type(boolean))
# This variable's type is bool, and it stores the value True


# Variable with special value
specialValue = None
print(specialValue)
print(type(specialValue))
# This variable's type is NoneType, and it stores the value None


# Variable with list type (additional variable)
listValue = [1, 2, 3]
print(listValue)
print(type(listValue))
# This variable's type is list, and it stores the value [1, 2, 3]